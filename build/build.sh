#!/usr/bin/env bash
# Runs INSIDE the emscripten/emsdk container (see scripts/build-wasm.sh); the repo is mounted at /work.
# Builds vendor/qpdf (unmodified) to src/wasm/ and regenerates THIRD_PARTY_NOTICES.md and README.md's
# qpdf version line.
set -euo pipefail
cd /work

QPDF_VERSION=$(bash build/qpdf-version.sh)
EMSCRIPTEN_VERSION=$(emcc --version | sed -nE '1s/.* ([0-9]+\.[0-9]+\.[0-9]+) .*/\1/p')
SRC=vendor/qpdf
OUT=out/cmake
DEST=src/wasm

# Patches (normally none) are applied to a copy so the submodule is never modified.
shopt -s nullglob
patches=(build/patches/*.patch)
if [ ${#patches[@]} -gt 0 ]; then
  rm -rf out/qpdf-src && mkdir -p out && cp -R "$SRC" out/qpdf-src
  for p in "${patches[@]}"; do patch -d out/qpdf-src -p1 < "$p"; done
  SRC=out/qpdf-src
fi

embuilder build zlib libjpeg
CACHE=$(em-config CACHE)
SYSROOT="$CACHE/sysroot"
LIBDIR="$SYSROOT/lib/wasm32-emscripten"

# Stack: qpdf recurses on nested PDF objects; Emscripten's default 64 KB stack overflowed into static
# data (crashes, corruption, endless loops). 8 MB plus --stack-first (the stack sits below static data,
# so an overflow traps instead of corrupting memory). -sSTACK_FIRST is internal in Emscripten 6.0.11;
# -Wl,--stack-first is the supported switch (tools/link.py).
emcmake cmake -S "$SRC" -B "$OUT" -G "Unix Makefiles" \
  -DCMAKE_BUILD_TYPE=Release \
  -DBUILD_SHARED_LIBS=OFF -DBUILD_STATIC_LIBS=ON -DBUILD_DOC=OFF \
  -DREQUIRE_CRYPTO_NATIVE=ON -DUSE_IMPLICIT_CRYPTO=OFF \
  -DZLIB_H_PATH="$SYSROOT/include" -DZLIB_LIB_PATH="$LIBDIR/libz.a" \
  -DLIBJPEG_H_PATH="$SYSROOT/include" -DLIBJPEG_LIB_PATH="$LIBDIR/libjpeg.a" \
  -DCMAKE_C_FLAGS="-O3 -fwasm-exceptions" \
  -DCMAKE_CXX_FLAGS="-O3 -fwasm-exceptions" \
  -DCMAKE_EXE_LINKER_FLAGS="-fwasm-exceptions -sSTACK_SIZE=8MB -Wl,--stack-first -sALLOW_MEMORY_GROWTH=1 -sMODULARIZE=1 -sEXPORT_ES6=1 -sEXPORT_NAME=createQpdfModule -sINVOKE_RUN=0 -sEXIT_RUNTIME=0 -sENVIRONMENT=web,worker -sEXPORTED_RUNTIME_METHODS=FS,callMain"
make -C "$OUT" -j"$(nproc)" qpdf

mkdir -p "$DEST"
cp "$OUT/qpdf/qpdf.js" "$DEST/qpdf.mjs"
cp "$OUT/qpdf/qpdf.wasm" "$DEST/qpdf.wasm"
cat > "$DEST/meta.mjs" <<EOF2
export const qpdfVersion = "$QPDF_VERSION";
export const emscriptenVersion = "$EMSCRIPTEN_VERSION";
EOF2

# Third-party notices, generated from the exact sources that were compiled.
require_file() { [ -n "$2" ] && [ -f "$2" ] || { echo "build.sh: $1 not found${2:+ at $2}; cannot generate THIRD_PARTY_NOTICES.md" >&2; exit 1; }; }
EMSCRIPTEN_ROOT=$(dirname "$(command -v emcc)")
ZLIB_LICENSE=$(find "$CACHE/ports/zlib" -maxdepth 2 -name LICENSE 2>/dev/null | head -1 || true)
JPEG_README=$(find "$CACHE/ports/libjpeg" -maxdepth 2 -name README 2>/dev/null | head -1 || true)
EMSCRIPTEN_LICENSE="$EMSCRIPTEN_ROOT/LICENSE"
MUSL_COPYRIGHT="$EMSCRIPTEN_ROOT/system/lib/libc/musl/COPYRIGHT"
require_file "zlib LICENSE" "$ZLIB_LICENSE"
require_file "libjpeg README" "$JPEG_README"
require_file "Emscripten LICENSE" "$EMSCRIPTEN_LICENSE"
require_file "musl COPYRIGHT" "$MUSL_COPYRIGHT"
ZLIB_DIR=$(basename "$(dirname "$ZLIB_LICENSE")")
JPEG_DIR=$(basename "$(dirname "$JPEG_README")")
{
  echo "# Third-party notices"
  echo
  echo "\`qpdf.wasm\` in this package is built from the following third-party software."
  echo "This file is generated by \`build/build.sh\`; do not edit it by hand."
  echo
  echo "This software is based in part on the work of the Independent JPEG Group."
  echo
  echo "## qpdf $QPDF_VERSION"
  echo
  echo "Source: https://github.com/qpdf/qpdf (tag v$QPDF_VERSION), compiled unmodified$( [ ${#patches[@]} -gt 0 ] && echo " with the patches in build/patches/" )."
  echo
  echo "### LICENSE.txt"
  echo; echo '````text'; cat "$SRC/LICENSE.txt"; echo '````'; echo
  echo "### NOTICE.md"
  echo; echo '````text'; cat "$SRC/NOTICE.md"; echo '````'; echo
  echo "## zlib ($ZLIB_DIR, via Emscripten $EMSCRIPTEN_VERSION ports)"
  echo; echo '````text'; cat "$ZLIB_LICENSE"; echo '````'; echo
  echo "## libjpeg ($JPEG_DIR, Independent JPEG Group, via Emscripten $EMSCRIPTEN_VERSION ports)"
  echo; echo '````text'; cat "$JPEG_README"; echo '````'; echo
  echo "## Emscripten $EMSCRIPTEN_VERSION"
  echo
  echo "The JavaScript glue (\`qpdf.mjs\`) and the system libraries linked into \`qpdf.wasm\` come from Emscripten."
  echo; echo '````text'; cat "$EMSCRIPTEN_LICENSE"; echo '````'; echo
  echo "## musl libc (via Emscripten $EMSCRIPTEN_VERSION)"
  echo; echo '````text'; cat "$MUSL_COPYRIGHT"; echo '````'; echo
  echo "## libc++ and libc++abi (LLVM, via Emscripten $EMSCRIPTEN_VERSION)"
  echo
  echo "Licensed under Apache-2.0 WITH LLVM-exception, which does not require attribution for compiled code."
} > THIRD_PARTY_NOTICES.md

# README states the bundled qpdf version between stable markers (checked by test/node/wasm-build.test.ts).
grep -q '<!-- qpdf-version -->.*<!-- /qpdf-version -->' README.md || { echo "build.sh: qpdf-version marker missing from README.md" >&2; exit 1; }
sed -i -E "s|<!-- qpdf-version -->.*<!-- /qpdf-version -->|<!-- qpdf-version -->Contains qpdf $QPDF_VERSION, built unmodified for WebAssembly.<!-- /qpdf-version -->|" README.md

if [ -n "${HOST_UID:-}" ]; then
  chown -R "$HOST_UID:$HOST_GID" "$DEST" out THIRD_PARTY_NOTICES.md README.md
fi
echo "Built qpdf $QPDF_VERSION with Emscripten $EMSCRIPTEN_VERSION"
